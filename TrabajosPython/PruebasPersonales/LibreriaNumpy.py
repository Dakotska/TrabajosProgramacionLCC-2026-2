import numpy as np

# ! Casos de uso de la libreria numpy

# * Exponenciales y logaritmos

#np.exp(x) Calcula e^x para cada elemento

#np.log(x) Calcula el logaritmo natural

#np.log10(x) Calcula el logaritmo base 10

#np.log2(x) Calcula el logaritmo base 2

# * Raices y potencias

#np.sqrt(x) Calcula la raiz cuadrada

#np.cbrt(x) Calcula la raiz cubica

#np.square(x) Eleva al cuadrado

#np.power(x, y) Eleva x a la potencia y

# * Trigonometria

#np.sin(x), np.cos(x), np.tan(x) Calcula el seno, coseno o tangente (en radianes)

#np.arcsin(x), np.arccos(x), np.arctan(x) Funciones inversas

#np.degrees(x), np.radians(x) Conversion entre radianes y grados

# * Redondeo y manipulacion

#np.abs(x) Valor absouluto

#np.floor(x) Redondea hacia abajo

#np.ceil Redondea hacia arriba

#np.round(x, decimals=N) Redondea a cierto numero de decimales