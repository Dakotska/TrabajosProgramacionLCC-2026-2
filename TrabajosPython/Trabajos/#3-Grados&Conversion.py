print("Bienvenido a la calculadora de F° a C°.")
GradosFahrenheit = int(input("Ingresa la cantidad de grados F°: "))
GradosCelsius = (GradosFahrenheit - 32) / 1.8
print(f"{GradosFahrenheit}F° son {GradosCelsius}C°")